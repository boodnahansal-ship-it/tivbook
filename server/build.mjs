// Bundles the server into ONE file for Supabase Edge Functions, and copies it (with the
// database schema) into the staff software, whose setup wizard installs both.
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const out = "dist/api/index.ts";
await build({
  entryPoints: ["src/deno.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  outfile: out,
  external: ["npm:*", "node:*"],
  mainFields: ["module", "main"],
  banner: { js: "// TiVBook server — generated by server/build.mjs. Do not edit.\n// deno-lint-ignore-file\nimport { Buffer } from \"node:buffer\";\n" },
  logLevel: "warning",
});
const fn = readFileSync(out, "utf8");
const schema = readFileSync("sql/schema.sql", "utf8");
const version = /version: "([\d.]+)"/.exec(readFileSync("src/router.ts", "utf8"))[1];
mkdirSync("../apps/staff/src/setup/generated", { recursive: true });
writeFileSync(
  "../apps/staff/src/setup/generated/bundle.ts",
  `// Generated by server/build.mjs — do not edit.\nexport const SERVER_VERSION = ${JSON.stringify(version)};\nexport const FUNCTION_SOURCE = ${JSON.stringify(fn)};\nexport const SCHEMA_SQL = ${JSON.stringify(schema)};\n`,
);
console.log(`server bundle: ${(fn.length / 1024).toFixed(1)} KB, schema: ${(schema.length / 1024).toFixed(1)} KB`);
